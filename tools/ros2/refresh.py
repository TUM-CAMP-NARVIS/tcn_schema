"""Generate src/dds/ros2 from upstream ROS 2 sources (decisions §5 R2–R7).

    python3 -I tools/ros2_cli.py refresh [--update-lock] [--hash-distros kilted,lyrical] [--cache DIR]
    python3 -I tools/ros2_cli.py check   [--cache DIR]

`refresh` fetches every package of every tier at the commit pinned in src/dds/ros2/UPSTREAM.lock (with
`--update-lock`, it first resolves the lock from rosdistro: each repository's Jazzy *release* version, as a tag of
its source repository) and regenerates the IDL, the per-package CMakeLists.txt and ros2_types.json. `check`
regenerates into a temporary directory and reports every file that differs from the committed tree. Only these two
commands use the network; the build does not.
"""
import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional

from .emit import emit_idl, expand_action, expand_service
from .hashing import hash_all
from .rosdistro import package_index, parse_distribution
from .tiers import TIERS, tier_of
from .tree import Tree, load_package

REPO_ROOT = Path(__file__).resolve().parents[2]
ROS2_DIR = REPO_ROOT / "src" / "dds" / "ros2"
LOCK = ROS2_DIR / "UPSTREAM.lock"
DISTRO = "jazzy"
ROSDISTRO_URL = "https://github.com/ros/rosdistro.git"


# -- generation (offline) -----------------------------------------------------------------------------------------

def _cmake(pkg: str, files: Dict[str, List[str]]) -> str:
    lines = ["# Generated by tools/ros2 (see src/dds/ros2/UPSTREAM.lock); do not edit.",
             "tcn_add_idl_package(", f"        NAME {pkg}"]
    for kind in ("msg", "srv", "action"):
        if files.get(kind):
            lines.append(f"        {kind.upper()}")
            lines += [f'            "{f}"' for f in files[kind]]
    lines.append("        )")
    return "\n".join(lines) + "\n"


def _types_entries(tree: Tree, tiers: Dict[str, str], hashes: Dict[str, Dict[str, str]]) -> List[dict]:
    names = []  # (ros_name, kind)
    for key in tree.msgs:
        names.append((key, "msg"))
    for key, s in tree.srvs.items():
        names.append((key, "srv"))
        names += [(f"{m.pkg}/srv/{m.name}", "srv_part") for m in expand_service(s)]
    for key, a in tree.actions.items():
        names.append((key, "action"))
        p, n = a.pkg, a.name
        names += [(f"{p}/action/{n}_SendGoal", "action_part"), (f"{p}/action/{n}_GetResult", "action_part")]
        names += [(f"{m.pkg}/action/{m.name}", "action_part") for m in expand_action(a)]
    out = []
    for ros_name, kind in sorted(names):
        pkg, ns, name = ros_name.split("/")
        out.append({
            "ros_name": ros_name, "kind": kind, "package": pkg, "tier": tiers[pkg],
            "dds_name": f"{pkg}::{ns}::dds_::{name}_", "cpp_name": f"{pkg}::{ns}::{name}",
            "hashes": {d: h[ros_name] for d, h in sorted(hashes.items()) if ros_name in h},
        })
    return out


def generate(sources: Dict[str, Path], tiers: Dict[str, str], out: Path,
             hash_trees: Dict[str, Optional[Tree]]) -> Tree:
    """Write <out>/<pkg>/{msg,srv,action}/*.idl, <out>/<pkg>/CMakeLists.txt and <out>/ros2_types.json for every
    package in `tiers`, from `sources` (pkg -> source dir). `hash_trees` maps a distro to the tree its hashes are
    computed from; None means the tree generated here."""
    tree = Tree()
    for pkg in tiers:
        load_package(tree, pkg, sources[pkg])
    for pkg in tiers:
        pdir = out / pkg
        if pdir.exists():
            shutil.rmtree(pdir)
        files: Dict[str, List[str]] = {"msg": [], "srv": [], "action": []}
        for key, m in sorted(tree.msgs.items()):
            if m.pkg == pkg:
                files["msg"].append(_write(pdir, pkg, "msg", m.name, [m]))
        for key, s in sorted(tree.srvs.items()):
            if s.pkg == pkg:
                files["srv"].append(_write(pdir, pkg, "srv", s.name, expand_service(s)))
        for key, a in sorted(tree.actions.items()):
            if a.pkg == pkg:
                files["action"].append(_write(pdir, pkg, "action", a.name, expand_action(a)))
        (pdir / "CMakeLists.txt").write_text(_cmake(pkg, files), encoding="utf-8")
    hashes = {d: hash_all(t if t is not None else tree) for d, t in hash_trees.items()}
    doc = {"distro": DISTRO, "generated_by": "tools/ros2 (src/dds/ros2/UPSTREAM.lock)",
           "types": _types_entries(tree, tiers, hashes)}
    (out / "ros2_types.json").write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return tree


def _write(pdir: Path, pkg: str, kind: str, stem: str, specs) -> str:
    rel = f"{kind}/{stem}.idl"
    path = pdir / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(emit_idl(pkg, kind, stem, specs), encoding="utf-8")
    return rel


def check_tree(committed: Path, regenerated: Path) -> List[str]:
    """Relative paths of generated files that differ, or exist on one side only (UPSTREAM.* are not generated)."""
    def files(root: Path):
        return {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()
                and not p.name.startswith("UPSTREAM.")}
    a, b = files(committed), files(regenerated)
    diff = [f for f in sorted(a | b) if f not in a or f not in b
            or (committed / f).read_bytes() != (regenerated / f).read_bytes()]
    return diff


# -- upstream (network) --------------------------------------------------------------------------------------------

def _git(*args, cwd=None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def cache_dir(cache: Path, url: str, ref: str) -> Path:
    """One directory per repository and ref: distros pin the same repository at different commits, and a shared
    checkout would replace the sources an earlier call handed out."""
    parts = url.rstrip("/").removesuffix(".git").split("/")
    safe = "".join(c if c.isalnum() or c in "._-" else "_" for c in ref)
    return cache / f"{parts[-2]}__{parts[-1]}@{safe}"


def _checkout(url: str, commit_or_ref: str, cache: Path) -> Path:
    """Shallow checkout of `commit_or_ref` (a sha, tag or branch) of `url` into the cache; returns the directory."""
    d = cache_dir(cache, url, commit_or_ref)
    if (d / ".git").is_dir():
        return d
    d.mkdir(parents=True, exist_ok=True)
    _git("init", "-q", cwd=d)
    _git("remote", "add", "origin", url, cwd=d)
    _git("fetch", "-q", "--depth", "1", "origin", commit_or_ref, cwd=d)
    _git("checkout", "-q", "--force", "FETCH_HEAD", cwd=d)
    return d


def _find_package(repo_dir: Path, pkg: str) -> Path:
    for xml in sorted(repo_dir.rglob("package.xml")):
        text = xml.read_text(encoding="utf-8", errors="replace")
        if f"<name>{pkg}</name>" in text:
            return xml.parent
    raise FileNotFoundError(f"{pkg}: no package.xml in {repo_dir}")


def _remote_tags(url: str) -> set:
    out = _git("ls-remote", "--tags", url)
    return {line.split("refs/tags/", 1)[1].removesuffix("^{}") for line in out.splitlines() if "refs/tags/" in line}


def resolve_lock(distro: str, rosdistro_commit: str, cache: Path) -> dict:
    """Pin every tier package: its repository's release version as a tag of the source repository (falling back to
    the source branch when the tag does not exist), resolved to a commit."""
    rd = _checkout(ROSDISTRO_URL, rosdistro_commit, cache)
    repos = parse_distribution((rd / distro / "distribution.yaml").read_text(encoding="utf-8"))
    index = package_index(repos)
    lock_repos, lock_pkgs = {}, {}
    for pkg, tier in tier_of().items():
        if pkg not in index:
            lock_pkgs[pkg] = {"tier": tier, "skipped": f"not released for {distro}"}
            continue
        r = repos[index[pkg]]
        url = r["source_url"]
        if url not in lock_repos:
            tag = (r["release_version"] or "").rsplit("-", 1)[0]
            ref = tag if tag and tag in _remote_tags(url) else r["source_version"]
            d = _checkout(url, ref, cache)
            lock_repos[url] = {"version": ref, "commit": _git("rev-parse", "HEAD", cwd=d),
                               "release_version": r["release_version"]}
        d = _checkout(url, lock_repos[url]["commit"], cache)
        lock_pkgs[pkg] = {"tier": tier, "repo": url, "path": _find_package(d, pkg).relative_to(d).as_posix()}
    return {"distro": distro, "rosdistro_commit": rosdistro_commit, "repos": lock_repos, "packages": lock_pkgs}


def _sources(lock: dict, cache: Path) -> Dict[str, Path]:
    out = {}
    for pkg, p in lock["packages"].items():
        if "skipped" in p:
            continue
        d = _checkout(p["repo"], lock["repos"][p["repo"]]["commit"], cache)
        out[pkg] = d / p["path"]
    return out


def _hash_trees(lock: dict, cache: Path) -> Dict[str, Optional[Tree]]:
    trees: Dict[str, Optional[Tree]] = {lock["distro"]: None}
    for distro, sub in sorted(lock.get("hash_distros", {}).items()):
        t = Tree()
        for pkg, path in _sources(sub, cache).items():
            load_package(t, pkg, path)
        trees[distro] = t
    return trees


def _tiers_of(lock: dict) -> Dict[str, str]:
    return {pkg: p["tier"] for pkg, p in lock["packages"].items() if "skipped" not in p}


def main(argv) -> int:
    ap = argparse.ArgumentParser(prog="ros2_cli.py")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("refresh")
    r.add_argument("--update-lock", action="store_true")
    r.add_argument("--rosdistro-commit", help="with --update-lock: pin this rosdistro commit (default: master)")
    r.add_argument("--hash-distros", default=None, help="comma-separated distros whose hashes to add (R7)")
    c = sub.add_parser("check")
    for p in (r, c):
        p.add_argument("--cache", type=Path, default=Path(tempfile.gettempdir()) / "tcn_schema_ros2_cache")
    args = ap.parse_args(argv)
    args.cache.mkdir(parents=True, exist_ok=True)

    if args.cmd == "refresh":
        if args.update_lock:
            commit = args.rosdistro_commit or _git("ls-remote", ROSDISTRO_URL, "refs/heads/master").split()[0]
            lock = resolve_lock(DISTRO, commit, args.cache)
            old = json.loads(LOCK.read_text()) if LOCK.exists() else {}
            if "hash_distros" in old:
                lock["hash_distros"] = old["hash_distros"]
        else:
            lock = json.loads(LOCK.read_text())
        if args.hash_distros is not None:
            lock["hash_distros"] = {}
            for d in [x for x in args.hash_distros.split(",") if x]:
                sub_lock = resolve_lock(d, lock["rosdistro_commit"], args.cache)
                lock["hash_distros"][d] = {k: sub_lock[k] for k in ("distro", "repos", "packages")}
        LOCK.write_text(json.dumps(lock, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        generate(_sources(lock, args.cache), _tiers_of(lock), ROS2_DIR, _hash_trees(lock, args.cache))
        print(f"generated {len(_tiers_of(lock))} packages into {ROS2_DIR}")
        return 0

    lock = json.loads(LOCK.read_text())
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "ros2"
        out.mkdir()
        generate(_sources(lock, args.cache), _tiers_of(lock), out, _hash_trees(lock, args.cache))
        committed = Path(tmp) / "committed"
        shutil.copytree(ROS2_DIR, committed, ignore=shutil.ignore_patterns("UPSTREAM.*"))
        diff = check_tree(committed, out)
    for f in diff:
        print(f"differs from upstream: src/dds/ros2/{f}")
    return 1 if diff else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
