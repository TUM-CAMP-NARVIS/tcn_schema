"""The joint-set table (decisions §7 HumanPose): load, check, and render the generated outputs.

`src/dds/tcn/tcnart_msgs/msg/joint_sets.yaml` is the source. From it come the IDL enum `tcnart_msgs::msg::JointSet`,
the docs page `JointSets.md`, the header-only C++ arrays `tcn/joint_sets.h`, the C# arrays `JointSets.cs` and
`joint_sets.json` (for every other language). `OUTPUTS` maps each repo-relative path to its renderer;
`idl_cli.py joint-sets --check` and tools/idl/tests/test_joint_sets.py fail when a committed file differs.
The file format is docs/proposals/2026-11-27-0.11-joint-sets-draft.md §2.
"""
import json
import math
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Tuple

from .yaml_subset import load as _load_yaml

TABLE_PATH = "src/dds/tcn/tcnart_msgs/msg/joint_sets.yaml"
REGENERATE = f"python3 -I tools/idl_cli.py joint-sets --table {TABLE_PATH}"
GENERATED = f"Generated by tools/idl/joint_sets.py from {TABLE_PATH}; do not edit."

ENUM_PREFIX = "JOINT_SET_"
MAX_JOINTS = 64       # HumanPose.joints
MAX_BONES = 64        # HumanShape.bone_lengths
PERSON_TRACKING_MAX = 32   # PersonTrackingMessage: Person.joints and Person.bone_lengths (documented, not refused)
MAX_SMPL_POSE = 54    # SmplParams.pose
SOURCES = ("OBSERVED", "DERIVED", "DEFAULTED")   # JointSource without its prefix
KINDS = ("tree", "positions")
UNIT_TOLERANCE = 1e-9

_TOP_KEYS = {"format", "body_frame", "joint_sets"}
_SET_KEYS = {"id", "ordinal", "version", "replaces", "kind", "purpose", "root", "rest_pose", "extends", "joints",
             "bones", "pose_excludes_root", "verified", "rotations", "maps_from", "maps_to"}
_INFO_KEYS = ("rotations", "maps_from", "maps_to")   # informational; rendered into the docs only
_JOINT_KEYS = {"name", "parent", "body", "source", "note"}
_BONE_KEYS = {"from", "to", "rest_dir"}
_RANGE_KEYS = {"range", "same_as"}
_HAND_KEYS = {"hand", "parent", "fingers", "joints_per_finger"}


@dataclass
class Joint:
    name: str
    parent: Optional[str]
    body: Optional[str]      # the corresponding TCN_BODY joint, e.g. "TCN_BODY.head"
    source: Optional[str]    # the usual JointSource (OBSERVED, DERIVED, DEFAULTED)
    note: Optional[str] = None


@dataclass
class Bone:
    frm: str
    to: str
    rest_dir: Optional[Tuple[float, float, float]]   # unit vector in the body frame B: the child's direction at rest


@dataclass
class JointSetDef:
    id: str                  # the enumerator without JOINT_SET_
    ordinal: int             # the enumerator's value: fixed, never reused
    version: int             # joint_set_version
    kind: str                # "tree" | "positions"
    root: Any                # a joint name, {"midpoint": [a, b]}, or None
    extends: Optional[str]
    rest_pose: Optional[str] # "t_pose", "smpl", "smplh", "smplx", or free text
    joints: List[Joint]
    bones: List[Bone]
    replaces: List[str]
    pose_excludes_root: bool
    verified: Optional[str] = None
    purpose: Optional[str] = None
    info: Dict[str, Any] = field(default_factory=dict)   # rotations, maps_from, maps_to (informational)


@dataclass
class Table:
    format: int
    body_frame: dict
    sets: List[JointSetDef]


# ---------------------------------------------------------------------------------------------------------- loading

def _keys(d: Any, allowed: set, where: str) -> dict:
    if not isinstance(d, dict):
        raise ValueError(f"{where}: expected a mapping, got {d!r}")
    unknown = sorted(set(d) - allowed)
    if unknown:
        raise ValueError(f"{where}: unknown keys {unknown}")
    return d


def _opt_str(v: Any, where: str) -> Optional[str]:
    if v is None:
        return None
    if not isinstance(v, str):
        raise ValueError(f"{where}: expected a string, got {v!r}")
    return v


def _range(text: Any, size: int, where: str) -> range:
    try:
        a, b = (int(x) for x in str(text).split("-"))
    except ValueError:
        raise ValueError(f"{where}: range {text!r} is not 'first-last'") from None
    if not 0 <= a <= b < size:
        raise ValueError(f"{where}: range {text!r} is outside 0-{size - 1}")
    return range(a, b + 1)


def load_table(text: str) -> Table:
    """Parse the YAML table and expand its shorthands ({range, same_as} and {hand, ...})."""
    doc = _keys(_load_yaml(text), _TOP_KEYS, "table")
    if doc.get("format") != 1:
        raise ValueError(f"table: format {doc.get('format')!r} is not supported (1)")
    raw_sets = doc.get("joint_sets") or []
    raw: Dict[str, dict] = {}
    for r in raw_sets:
        r = _keys(r, _SET_KEYS, "joint set")
        if not isinstance(r.get("id"), str):
            raise ValueError(f"joint set without an id: {r!r}")
        if r["id"] in raw:
            raise ValueError(f"{r['id']}: defined twice")
        raw[r["id"]] = r

    joints: Dict[str, List[Joint]] = {}
    bones: Dict[str, List[Bone]] = {}

    def resolve(set_id: str, what: str, stack: Tuple[str, ...]) -> list:
        memo = joints if what == "joints" else bones
        if set_id in memo:
            return memo[set_id]
        if set_id not in raw:
            raise ValueError(f"{stack[-1]}: same_as {set_id!r} is not a joint set")
        if set_id in stack:
            raise ValueError(f"{set_id}: same_as cycle {' -> '.join(stack + (set_id,))}")
        out = []
        for k, e in enumerate(raw[set_id].get(what) or []):
            where = f"{set_id}: {what}[{k}]"
            if isinstance(e, dict) and "same_as" in e:
                _keys(e, _RANGE_KEYS, where)
                src = resolve(e["same_as"], what, stack + (set_id,))
                out += [src[i] for i in _range(e.get("range"), len(src), where)]
            elif what == "joints" and isinstance(e, dict) and "hand" in e:
                _keys(e, _HAND_KEYS, where)
                n = e.get("joints_per_finger")
                if not isinstance(n, int) or n < 1 or not e.get("fingers"):
                    raise ValueError(f"{where}: needs fingers and joints_per_finger >= 1")
                for finger in e["fingers"]:
                    parent = _opt_str(e.get("parent"), where)
                    for i in range(1, n + 1):
                        name = f"{e['hand']}_{finger}{i}"
                        out.append(Joint(name, parent, None, None))
                        parent = name
            elif what == "joints":
                _keys(e, _JOINT_KEYS, where)
                if not isinstance(e.get("name"), str):
                    raise ValueError(f"{where}: joint without a name")
                out.append(Joint(e["name"], _opt_str(e.get("parent"), where), _opt_str(e.get("body"), where),
                                 _opt_str(e.get("source"), where), _opt_str(e.get("note"), where)))
            else:
                _keys(e, _BONE_KEYS, where)
                rd = e.get("rest_dir")
                if rd is not None:
                    if not (isinstance(rd, list) and len(rd) == 3
                            and all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in rd)):
                        raise ValueError(f"{where}: rest_dir must be three numbers, got {rd!r}")
                    rd = tuple(float(x) for x in rd)
                if not isinstance(e.get("from"), str) or not isinstance(e.get("to"), str):
                    raise ValueError(f"{where}: a bone needs from and to")
                out.append(Bone(e["from"], e["to"], rd))
        memo[set_id] = out
        return out

    sets = []
    for set_id, r in raw.items():
        for k in ("ordinal", "version"):
            if not isinstance(r.get(k), int) or isinstance(r.get(k), bool):
                raise ValueError(f"{set_id}: {k} must be an integer")
        replaces = r.get("replaces") or []
        if not (isinstance(replaces, list) and all(isinstance(x, str) for x in replaces)):
            raise ValueError(f"{set_id}: replaces must be a list of names")
        sets.append(JointSetDef(
            id=set_id, ordinal=r["ordinal"], version=r["version"], kind=r.get("kind", "tree"), root=r.get("root"),
            extends=_opt_str(r.get("extends"), set_id), rest_pose=_opt_str(r.get("rest_pose"), set_id),
            joints=list(resolve(set_id, "joints", ())), bones=list(resolve(set_id, "bones", ())),
            replaces=list(replaces), pose_excludes_root=bool(r.get("pose_excludes_root", False)),
            verified=_opt_str(r.get("verified"), set_id), purpose=_opt_str(r.get("purpose"), set_id),
            info={k: r[k] for k in _INFO_KEYS if k in r}))
    return Table(format=doc["format"], body_frame=doc.get("body_frame") or {}, sets=sets)


# --------------------------------------------------------------------------------------------------------- checking

def _content(s: JointSetDef):
    """What a version pins: joints (names, parents), bones and the rest pose."""
    return (s.kind, s.root if not isinstance(s.root, dict) else json.dumps(s.root, sort_keys=True), s.rest_pose,
            tuple((j.name, j.parent) for j in s.joints), tuple((b.frm, b.to, b.rest_dir) for b in s.bones))


def _check_tree(s: JointSetDef) -> List[str]:
    """The tree rules; bones are checked only once the parents form one tree."""
    errors = []
    names = [j.name for j in s.joints]
    known = set(names)
    roots = [j.name for j in s.joints if j.parent is None]
    if len(roots) != 1:
        errors.append(f"{s.id}: a tree set has exactly one root; it has {len(roots)} ({', '.join(roots) or 'none'})")
    unknown = [f"{j.name} -> {j.parent}" for j in s.joints if j.parent is not None and j.parent not in known]
    if unknown:
        errors.append(f"{s.id}: parents that are no joint of the set: {', '.join(unknown)}")
    elif len(known) == len(names):
        parent = {j.name: j.parent for j in s.joints}
        cyclic = []
        for n in names:
            seen, p = set(), n
            while p is not None and p not in seen:
                seen.add(p)
                p = parent[p]
            if p == n:
                cyclic.append(n)
        if cyclic:
            errors.append(f"{s.id}: the parents form a cycle through {', '.join(cyclic)}")
    if len(roots) == 1 and isinstance(s.root, str) and s.root != roots[0]:
        errors.append(f"{s.id}: root {s.root!r} is not the joint without a parent ({roots[0]})")
    elif s.root is not None and not isinstance(s.root, str):
        errors.append(f"{s.id}: the root of a tree set is a joint name, got {s.root!r}")
    if errors or len(known) != len(names):
        return errors
    parent = {j.name: j.parent for j in s.joints}
    for i, b in enumerate(s.bones):
        if b.to not in known:
            errors.append(f"{s.id}: bone {i} ends at {b.to!r}, no joint of the set")
        elif b.frm != parent[b.to]:
            errors.append(f"{s.id}: bone {i} ({b.frm} -> {b.to}) does not start at the parent of {b.to} "
                          f"({parent[b.to]})")
    return errors


def _check_positions(s: JointSetDef) -> List[str]:
    errors = []
    known = {j.name for j in s.joints}
    with_parent = [j.name for j in s.joints if j.parent is not None]
    if with_parent:
        errors.append(f"{s.id}: a positions set has no parents ({', '.join(with_parent)})")
    for i, b in enumerate(s.bones):
        if b.frm not in known or b.to not in known or b.frm == b.to:
            errors.append(f"{s.id}: bone {i} ({b.frm} -> {b.to}) does not join two joints of the set")
    r = s.root
    ok = (r is None or (isinstance(r, str) and r in known)
          or (isinstance(r, dict) and set(r) == {"midpoint"} and isinstance(r["midpoint"], list)
              and len(r["midpoint"]) == 2 and all(x in known for x in r["midpoint"])))
    if not ok:
        errors.append(f"{s.id}: root {r!r} is neither a joint nor {{midpoint: [a, b]}} of two joints")
    return errors


def check_table(t: Table, previous: Optional[Table] = None) -> List[str]:
    """The table rules (draft §2, with "one acyclic tree" instead of "parents first"); [] when the table is valid."""
    errors: List[str] = []
    by_id: Dict[str, JointSetDef] = {}
    for s in t.sets:
        if s.id in by_id:
            errors.append(f"{s.id}: defined twice")
        by_id[s.id] = s
    n = len(t.sets)
    by_ordinal: Dict[int, str] = {}
    for s in t.sets:
        if not 1 <= s.ordinal <= n:
            errors.append(f"{s.id}: ordinal {s.ordinal} is outside 1..{n} (the ordinals are exactly 1..N)")
        elif s.ordinal in by_ordinal:
            errors.append(f"{s.id}: ordinal {s.ordinal} is also {by_ordinal[s.ordinal]}'s")
        else:
            by_ordinal[s.ordinal] = s.id
        if not 1 <= s.version <= 0xFFFF:
            errors.append(f"{s.id}: version {s.version} is outside 1..65535 (uint16 joint_set_version)")

    for s in t.sets:
        if s.kind not in KINDS:
            errors.append(f"{s.id}: kind {s.kind!r} is not one of {', '.join(KINDS)}")
            continue
        names = [j.name for j in s.joints]
        for name in sorted({x for x in names if names.count(x) > 1}):
            errors.append(f"{s.id}: duplicate joint name {name!r}")
        if len(names) > MAX_JOINTS:
            errors.append(f"{s.id}: {len(names)} joints; HumanPose.joints holds at most {MAX_JOINTS}")
        if len(s.bones) > MAX_BONES:
            errors.append(f"{s.id}: {len(s.bones)} bones; HumanShape.bone_lengths holds at most {MAX_BONES}")
        if s.pose_excludes_root and len(names) - 1 > MAX_SMPL_POSE:
            errors.append(f"{s.id}: SmplParams.pose would hold {len(names) - 1} rotations; it holds at most "
                          f"{MAX_SMPL_POSE}")
        for j in s.joints:
            if j.source is not None and j.source not in SOURCES:
                errors.append(f"{s.id}: joint {j.name} has source {j.source!r}, not one of {', '.join(SOURCES)}")
        errors += _check_tree(s) if s.kind == "tree" else _check_positions(s)
        for i, b in enumerate(s.bones):
            if b.rest_dir is None:
                if s.rest_pose == "t_pose":
                    errors.append(f"{s.id}: bone {i} ({b.frm} -> {b.to}) has no rest_dir; rest_pose t_pose needs one")
            elif len(b.rest_dir) != 3 or abs(math.sqrt(sum(x * x for x in b.rest_dir)) - 1.0) > UNIT_TOLERANCE:
                errors.append(f"{s.id}: bone {i} ({b.frm} -> {b.to}) rest_dir {list(b.rest_dir)} is not a unit vector")
        if s.extends is not None:
            base = by_id.get(s.extends)
            if base is None:
                errors.append(f"{s.id}: extends {s.extends!r}, which is not a joint set")
            else:
                diffs = []
                if len(base.joints) > len(s.joints) or len(base.bones) > len(s.bones):
                    diffs.append("it has fewer joints or bones")
                diffs += [f"joint {i}" for i, j in enumerate(base.joints[:len(s.joints)])
                          if (j.name, j.parent) != (s.joints[i].name, s.joints[i].parent)]
                diffs += [f"bone {i}" for i, b in enumerate(base.bones[:len(s.bones)])
                          if (b.frm, b.to, b.rest_dir) != (s.bones[i].frm, s.bones[i].to, s.bones[i].rest_dir)]
                if diffs:
                    errors.append(f"{s.id}: extends {base.id}, but {base.id} is not its prefix (differs at "
                                  f"{', '.join(diffs)})")

    if previous is not None:
        for p in previous.sets:
            s = by_id.get(p.id)
            if s is None:
                errors.append(f"{p.id}: in the previous table but gone (a set and its ordinal are never removed)")
                continue
            if s.ordinal != p.ordinal:
                errors.append(f"{s.id}: ordinal {s.ordinal} was {p.ordinal} (an ordinal is fixed)")
            if s.version < p.version:
                errors.append(f"{s.id}: version {s.version} is lower than the previous {p.version}")
            elif _content(s) != _content(p) and s.version == p.version:
                errors.append(f"{s.id}: joints, bones or rest pose changed, but version {s.version} did not")
    return errors


# -------------------------------------------------------------------------------------------------------- rendering

def _sorted(t: Table) -> List[JointSetDef]:
    return sorted(t.sets, key=lambda s: s.ordinal)


def _pascal(set_id: str) -> str:
    return "".join(p[:1].upper() + p[1:].lower() for p in set_id.split("_"))


def _ident(s: JointSetDef) -> str:
    return f"{s.id.lower()}_v{s.version}"


def _indices(s: JointSetDef) -> Dict[str, int]:
    return {j.name: i for i, j in enumerate(s.joints)}


def _float_c(x: float) -> str:
    r = repr(float(x))
    return r + "f" if any(c in r for c in ".e") else r + ".0f"


def _plural(n: int, word: str) -> str:
    return f"{n} {word}" + ("" if n == 1 else "s")


def _root_text(s: JointSetDef) -> str:
    if isinstance(s.root, dict) and "midpoint" in s.root:
        a, b = s.root["midpoint"]
        idx = _indices(s)
        return f"mid-point of {a} and {b} ({idx.get(a)}, {idx.get(b)})"
    roots = [j.name for j in s.joints if j.parent is None] if s.kind == "tree" else []
    name = s.root if isinstance(s.root, str) else (roots[0] if len(roots) == 1 else None)
    return f"{name} ({_indices(s).get(name)})" if name else "-"


def render_idl(t: Table) -> str:
    sets = _sorted(t)
    width = max(len(ENUM_PREFIX + s.id) for s in sets) + 1
    lines = [
        f"// {GENERATED}",
        f"// Regenerate: {REGENERATE}",
        "",
        "#ifndef TCNART_MSGS_MSG_JOINTSET_IDL",
        "#define TCNART_MSGS_MSG_JOINTSET_IDL",
        "",
        "module tcnart_msgs {",
        "  module msg {",
        "",
        "    // The joint set of a person stream (decisions §7 HumanPose). With the stream's joint_set_version it fixes",
        "    // the order of the joints and bones, the parents and the rest pose (tcnart_msgs/msg/JointSets.md).",
        "    // An ordinal is never reused. Consumers refuse an unknown (joint set, version) pair.",
        "    @appendable enum JointSet {",
        f"      {ENUM_PREFIX}UNKNOWN,",
    ]
    for k, s in enumerate(sets):
        sep = "," if k + 1 < len(sets) else ""
        what = ", positions only" if s.kind == "positions" else (", SmplParams.pose order" if s.pose_excludes_root
                                                                  else "")
        lines.append(f"      {(ENUM_PREFIX + s.id + sep).ljust(width)} // {s.ordinal}: "
                     f"{_plural(len(s.joints), 'joint')}{what}")
    lines += ["    };", "", "  };", "};", "", "#endif", ""]
    return "\n".join(lines)


def _json_set(s: JointSetDef) -> dict:
    idx = _indices(s)
    return {
        "id": s.id,
        "enum": ENUM_PREFIX + s.id,
        "ordinal": s.ordinal,
        "version": s.version,
        "kind": s.kind,
        "replaces": s.replaces,
        "purpose": s.purpose,
        "root": s.root,
        "extends": s.extends,
        "rest_pose": s.rest_pose,
        "pose_excludes_root": s.pose_excludes_root,
        "verified": s.verified,
        "joints": [{"name": j.name, "parent": j.parent, "parent_index": idx.get(j.parent, -1) if j.parent else -1,
                    "body": j.body, "source": j.source, "note": j.note} for j in s.joints],
        "bones": [{"from": b.frm, "to": b.to, "from_index": idx[b.frm], "to_index": idx[b.to],
                   "rest_dir": list(b.rest_dir) if b.rest_dir is not None else None} for b in s.bones],
        "info": s.info,
    }


def render_json(t: Table) -> str:
    doc = {
        "_comment": f"{GENERATED} The joint sets of tcnart_msgs::msg::JointSet; a consumer refuses an unknown "
                    "(id, version) pair. rest_dir: unit vector in body_frame, null where the set states none.",
        "format": t.format,
        "body_frame": t.body_frame,
        "joint_sets": [_json_set(s) for s in _sorted(t)],
    }
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def _c_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)


def _wrap(items: List[str], indent: str, width: int = 116) -> List[str]:
    out, line = [], indent
    for it in items:
        piece = it + ","
        if line.strip() and len(line) + 1 + len(piece) > width:
            out.append(line.rstrip())
            line = indent
        line += ("" if line == indent else " ") + piece
    if line.strip():
        out.append(line.rstrip())
    return out


def render_cpp(t: Table) -> str:
    sets = _sorted(t)
    enumerators = ", ".join(["Unknown = 0"] + [f"{_pascal(s.id)} = {s.ordinal}" for s in sets])
    L = [
        f"// {GENERATED}",
        f"// Regenerate: {REGENERATE}",
        "//",
        "// The joint sets of tcnart_msgs::msg::JointSet (decisions §7 HumanPose), header-only and dependency-free.",
        "// find(set, version) returns nullptr for an unknown pair: refuse the stream then.",
        "// Rotations are rest-pose-relative in the stream's frame: joint i's outgoing bones point along",
        "// rotation * rest_dir (rest_dir in the body frame B: +x the person's left, +y up, +z forward). rest_dir is",
        "// NaN where the set states none (positions-only sets). parents[i] is -1 for the root and in positions-only",
        "// sets; a tree set need not list parents first.",
        "#ifndef TCN_JOINT_SETS_H",
        "#define TCN_JOINT_SETS_H",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <limits>",
        "",
        "namespace tcn::joint_sets {",
        "",
        "// The values of tcnart_msgs::msg::JointSet.",
        f"enum class JointSet : std::int32_t {{ {enumerators} }};",
        "",
        "struct Bone {",
        "    std::int16_t from;  // the parent joint in a tree set",
        "    std::int16_t to;",
        "    float rest_dir[3];",
        "};",
        "",
        "struct JointSetInfo {",
        "    JointSet id;",
        "    std::uint16_t version;",
        "    bool positions_only;",
        "    std::size_t joint_count;",
        "    const char* const* joint_names;",
        "    const std::int16_t* parents /* -1: none */;",
        "    std::size_t bone_count;",
        "    const Bone* bones;  // nullptr when bone_count is 0",
        "};",
        "",
        "namespace detail {",
        "inline constexpr float kNaN = std::numeric_limits<float>::quiet_NaN();",
    ]
    for s in sets:
        idx = _indices(s)
        L += ["", f"// {s.id} version {s.version}"]
        L.append(f"inline constexpr const char* {_ident(s)}_names[] = {{")
        L += _wrap([_c_str(j.name) for j in s.joints], "    ")
        L.append("};")
        L.append(f"inline constexpr std::int16_t {_ident(s)}_parents[] = {{")
        L += _wrap([str(idx[j.parent]) if j.parent in idx else "-1" for j in s.joints], "    ")
        L.append("};")
        if s.bones:
            L.append(f"inline constexpr Bone {_ident(s)}_bones[] = {{")
            for b in s.bones:
                rd = ", ".join(_float_c(x) for x in b.rest_dir) if b.rest_dir is not None else "kNaN, kNaN, kNaN"
                L.append(f"    {{{idx[b.frm]}, {idx[b.to]}, {{{rd}}}}},  // {b.frm} -> {b.to}")
            L.append("};")
    L += ["}  // namespace detail", "", "inline constexpr JointSetInfo kJointSets[] = {"]
