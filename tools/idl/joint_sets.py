_AXES = {(1.0, 0.0, 0.0): "+x", (-1.0, 0.0, 0.0): "−x", (0.0, 1.0, 0.0): "+y", (0.0, -1.0, 0.0): "−y",
         (0.0, 0.0, 1.0): "+z", (0.0, 0.0, -1.0): "−z"}


def _dir_text(d: Optional[Tuple[float, float, float]]) -> str:
    if d is None:
        return ""
    return _AXES.get(tuple(float(x) for x in d)) or "(" + ", ".join(f"{x:g}" for x in d) + ")"


def _info_text(v: Any) -> str:
    if isinstance(v, dict):
        return "; ".join(f"{k}: {_info_text(x)}" for k, x in v.items())
    if isinstance(v, list):
        return ", ".join(_info_text(x) for x in v)
    return str(v)


def _md_cell(v: Any) -> str:
    return "" if v is None else str(v).replace("|", "\\|")


def _md_set(s: JointSetDef, by_id: Dict[str, JointSetDef]) -> List[str]:
    idx = _indices(s)
    L = [f"## `{s.id}`", ""]
    if s.purpose:
        L += [s.purpose[:1].upper() + s.purpose[1:] + ".", ""]
    facts = [f"- **Enum:** `{ENUM_PREFIX}{s.id}` = {s.ordinal}, `joint_set_version` {s.version}.",
             f"- **Kind:** `{s.kind}`" + (" (positions only: no parents, no rest pose, no rotations; the bones are "
                                         "measured segments)." if s.kind == "positions" else ".")]
    L += facts
    L.append(f"- **Root:** {_root_text(s)}.")
    if s.rest_pose:
        rp = {"t_pose": "a T-pose in B: at rest every joint's frame equals B (the bones' rest directions below)",
              "smpl": "SMPL's own template, not stated here (licensed model data)",
              "smplh": "SMPL+H's own template, not stated here (licensed model data)",
              "smplx": "SMPL-X's own template, not stated here (licensed model data)"}.get(s.rest_pose, s.rest_pose)
        L.append(f"- **Rest pose:** {rp}.")
    if s.extends:
        base = by_id.get(s.extends)
        nb = f" and bones 0–{len(base.bones) - 1}" if base and base.bones else ""
        nj = f"joints 0–{len(base.joints) - 1}" if base else "its first joints"
        L.append(f"- **Extends** `{s.extends}`: {nj}{nb} are `{s.extends}`'s, so a `{s.extends}` reader reads this "
                 "set by its prefix.")
    if s.replaces:
        L.append(f"- **Replaces** the retired string name{'s' if len(s.replaces) > 1 else ''} "
                 f"{', '.join(f'`{r}`' for r in s.replaces)}.")
    if s.pose_excludes_root:
        L.append(f"- **`SmplParams.pose`** holds joints 1–{len(s.joints) - 1} ({len(s.joints) - 1} entries); joint 0 "
                 "is `global_orient`.")
    if s.verified:
        L.append(f"- **Verified:** {s.verified}.")
    for k, v in s.info.items():
        L.append(f"- **{k.replace('_', ' ').capitalize()}** (informational): {_info_text(v)}.")
    L.append("")

    cols = [("index", lambda i, j: str(i)), ("joint", lambda i, j: f"`{j.name}`")]
    if s.kind == "tree":
        cols.append(("parent", lambda i, j: f"{idx[j.parent]} `{j.parent}`" if j.parent in idx else "–"))
    if any(j.body for j in s.joints):
        cols.append(("TCN_BODY joint", lambda i, j: f"`{j.body}`" if j.body else ""))
    if any(j.source for j in s.joints):
        cols.append(("source", lambda i, j: j.source or ""))
    if any(j.note for j in s.joints):
        cols.append(("note", lambda i, j: _md_cell(j.note)))
    L += [f"Joints ({len(s.joints)}), in wire order:", "",
          "| " + " | ".join(c for c, _ in cols) + " |", "|" + "---|" * len(cols)]
    L += ["| " + " | ".join(f(i, j) for _, f in cols) + " |" for i, j in enumerate(s.joints)]
    L.append("")
    if s.bones:
        has_dir = any(b.rest_dir is not None for b in s.bones)
        head = "| i | from | to | joints |" + (" rest direction in B |" if has_dir else "")
        L += [f"Bones ({len(s.bones)}), in `bone_lengths` order"
              + ("; the bone's rotation is the rotation of `from`:" if s.kind == "tree" else ":"), "",
              head, "|" + "---|" * (5 if has_dir else 4)]
        for i, b in enumerate(s.bones):
            row = f"| {i} | `{b.frm}` | `{b.to}` | {idx.get(b.frm)}, {idx.get(b.to)} |"
            L.append(row + (f" {_dir_text(b.rest_dir)} |" if has_dir else ""))
    else:
        L.append("Bones: none (no `bone_lengths`).")
    L.append("")
    return L


