"""Generate a C++ round-trip test for every struct and union of one package (decisions O8).

The generated source defines `void roundtrip_<pkg>()`; each type goes through `TCN_ROUNDTRIP(T)` (test/cdr_util.h):
a default-constructed T is encoded with the current wire encoding, decoded into a fresh T, and compared.
"""
import json
from pathlib import Path, PurePosixPath


# Files whose generated code cannot be compiled, with the reason. Each entry is removed by the change that fixes it.
SKIPPED_FILES: dict = {}


def generate(types: dict, package: str) -> str:
    entries = [t for t in types["types"] if t["package"] == package and t["kind"] in ("struct", "union")
               and t["file"] not in SKIPPED_FILES]
    files = []
    for t in types["types"]:
        if t["package"] == package and t["file"] not in files:
            files.append(t["file"])
    lines = [f"// Generated by tools/idl/roundtrip.py from types.json; do not edit.",
             '#include "cdr_util.h"', ""]
    for f in files:
        if f in SKIPPED_FILES:
            lines.append(f"// skipped: {f}: {SKIPPED_FILES[f]}")
    files = [f for f in files if f not in SKIPPED_FILES]
    with_aggregates = {t["file"] for t in types["types"] if t["kind"] in ("struct", "union")}
    for f in files:
        p = PurePosixPath(f)
        stem = str(p.with_suffix(""))
        lines.append(f'#include "{stem}.h"')
        if f in with_aggregates:  # fastddsgen writes no CdrAux.hpp for a file of enums and consts only
            lines.append(f'#include "{stem}CdrAux.hpp"')
    lines += ["", f"void roundtrip_{package}()", "{"]
    for t in entries:
        # operator== of these types compares pointers (types.json "eq_by_pointer"): check the bytes only.
        macro = "TCN_ROUNDTRIP_BYTES" if t.get("eq_by_pointer") else "TCN_ROUNDTRIP"
        lines.append(f"    {macro}({t['name']});")
    lines += ["}", ""]
    return "\n".join(lines)


def write(types_json: Path, package: str, out: Path) -> None:
    types = json.loads(types_json.read_text(encoding="utf-8"))
    src = generate(types, package)
    if not out.exists() or out.read_text(encoding="utf-8") != src:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(src, encoding="utf-8")
