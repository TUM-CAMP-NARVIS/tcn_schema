"""Rename, insert and reorder enumerators (0.11 plan 4: E6 `..._UNKNOWN` first, O5 enum-name prefix).

A table is the enum's new enumerators in their new order, each `[old_name_or_None, new_name]`; None inserts one.
Every old enumerator must appear exactly once. Per-enumerator comments move with their enumerator, and union case
labels that name an old enumerator follow the rename. Ordinals are positions (no explicit values in tcn enums).
"""
import re
from typing import Dict, List, Optional, Sequence, Tuple

from .model import Enum, Union

_ITEM = re.compile(r"^(\s*)([A-Za-z_]\w*)(\s*,)?(\s*)(//.*)?$")


def _check(e: Enum, table: Sequence) -> None:
    olds = [o for o, _ in table if o is not None]
    news = [n for _, n in table]
    if sorted(olds) != sorted(n for n, _ in e.enumerators) or len(set(news)) != len(news):
        raise ValueError(f"{e.name}: the table must list every old enumerator once and no new name twice")
    if any(v != i for i, (_, v) in enumerate(e.enumerators)):
        raise ValueError(f"{e.name}: explicit enumerator values are not supported")


def _body_edit(text: str, e: Enum, table: Sequence) -> Tuple[int, int, str]:
    short = e.name.rsplit("::", 1)[-1]
    m = re.compile(rf"\benum\s+{re.escape(short)}\s*\{{").search(text, e.span[0], e.span[1])
    if m is None:
        raise ValueError(f"{e.name}: enum body not found")
    open_, close = m.end(), text.index("}", m.end())
    lines = text[open_:close].split("\n")
    if len(lines) < 3:
        raise ValueError(f"{e.name}: write the enum one enumerator per line before renaming it")
    head, tail = lines[0], lines[-1]
    items: Dict[str, Tuple[List[str], re.Match]] = {}
    pending: List[str] = []
    for line in lines[1:-1]:
        code = line.split("//", 1)[0].strip()
        if not code:
            pending.append(line)
            continue
        im = _ITEM.match(line)
        if im is None:
            raise ValueError(f"{e.name}: cannot read enumerator line {line!r}")
        items[im.group(2)] = (pending, im)
        pending = []
    trailing = pending
    indent = next(iter(items.values()))[1].group(1)
    out = [head]
    for i, (old, new) in enumerate(table):
        comma = "," if i < len(table) - 1 else ""
        if old is None:
            out.append(f"{indent}{new}{comma}")
            continue
        before, im = items[old]
        out += before
        rest = (im.group(4) or "") + im.group(5) if im.group(5) else ""  # keep the comment and its column
        out.append(f"{im.group(1)}{new}{comma}{rest}".rstrip())
    out += trailing + [tail]
    return open_, close, "\n".join(out)


def _label_edits(text: str, u: Union, renames: Dict[str, str]) -> List[Tuple[int, int, str]]:
    edits = []
    for m in re.finditer(r"(\bcase\s+(?:[\w:]*::)?)([A-Za-z_]\w*)(\s*:)", text[u.span[0]:u.span[1]]):
        if m.group(2) in renames:
            s = u.span[0] + m.start(2)
            edits.append((s, s + len(m.group(2)), renames[m.group(2)]))
    return edits


def apply_enums(text: str, decls, tables: Dict[str, Sequence]) -> str:
    """Apply every table to its enum (when declared in this file) and to the case labels of every union that
    switches on it. All edits are computed against the spans of `text`, then applied back to front."""
    edits = []
    for d in decls:
        if isinstance(d, Enum) and d.name in tables:
            _check(d, tables[d.name])
            edits.append(_body_edit(text, d, tables[d.name]))
        elif isinstance(d, Union) and d.discriminator in tables:
            edits += _label_edits(text, d, {o: n for o, n in tables[d.discriminator] if o is not None})
    for s, e, new in sorted(edits, reverse=True):
        text = text[:s] + new + text[e:]
    return text


def apply_enum(text: str, decls, fq: str, table: Sequence) -> str:
    return apply_enums(text, decls, {fq: table})


def migration_rows(e: Enum, table: Sequence) -> List[Tuple[Optional[str], Optional[int], str, int]]:
    old_value = {n: v for n, v in e.enumerators}
    return [(o, old_value.get(o) if o else None, n, i) for i, (o, n) in enumerate(table)]


def write_markdown(rows_by_enum: Dict[str, list], path, plan: str, table_name: str) -> None:
    lines = ["# 0.11 enum map", "",
             f"Generated by `python3 -I tools/idl_cli.py enums` (0.11 {plan}) from `tools/idl/{table_name}`.",
             "Every renamed enum, every enumerator with its 0.10 name and value and its 0.11 name and value. The",
             "values are what goes on the wire: **a value that changed is a breaking change for a codec that writes",
             "numbers**, so use the names. `-` marks an enumerator new in 0.11 (decisions E6: `..._UNKNOWN` first).", ""]
    for fq in sorted(rows_by_enum):
        lines += [f"## `{fq}`", "", "| 0.10 | value | 0.11 | value |", "|---|---|---|---|"]
        for o, ov, n, nv in rows_by_enum[fq]:
            moved = "" if ov == nv else " **(changed)**"
            lines.append(f"| {'`' + o + '`' if o else '-'} | {'' if ov is None else ov} | `{n}` | {nv}{moved} |")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
